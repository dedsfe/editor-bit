// marcas de acento: 2 linhas acima da letra (cedilha: embaixo)
const MARK: Record<string, string[]> = {
  acute: ["...#.", "..#.."], grave: [".#...", "..#.."], circ: ["..#..", ".#.#."],
  tilde: [".##.#", "#..#."], uml: [".#.#.", "....."],
};
const ACCENT: Record<string, [string, string]> = {
  Á: ["A", "acute"], À: ["A", "grave"], Â: ["A", "circ"], Ã: ["A", "tilde"], Ä: ["A", "uml"],
  É: ["E", "acute"], È: ["E", "grave"], Ê: ["E", "circ"],
  Í: ["I", "acute"], Ì: ["I", "grave"], Î: ["I", "circ"],
  Ó: ["O", "acute"], Ò: ["O", "grave"], Ô: ["O", "circ"], Õ: ["O", "tilde"],
  Ú: ["U", "acute"], Ù: ["U", "grave"], Û: ["U", "circ"], Ü: ["U", "uml"],
  Ñ: ["N", "tilde"],
};

export const LINE_H = 12; // 3 de acento + 7 de letra + 2 de cedilha/vírgula
const TOP = 3;

export interface Glyph { w: number; px: [number, number][] }

const cache = new Map<string, Glyph>();

export function glyph(ch: string): Glyph {
  let g = cache.get(ch);
  if (g) return g;
  let c = ch.toUpperCase().replace(/\uFE0F/g, "");
  if (c === "…") c = "...";
  if (!c) g = { w: -1, px: [] }; // seletor de variação de emoji: não ocupa espaço
  else if ([...c].length > 1) {
    // "…" vira três pontos colados
    const parts = [...c].map(glyph);
    let x = 0;
    const px: [number, number][] = [];
    parts.forEach((p) => { p.px.forEach(([a, b]) => px.push([a + x, b])); x += p.w + 1; });
    g = { w: x - 1, px };
  } else {
    const acc = ACCENT[c];
    const base = acc ? acc[0] : c === "Ç" ? "C" : c;
    const rows = (G[base] ?? G["?"]).split("|");
    const w = rows[0].length;
    const px: [number, number][] = [];
    rows.forEach((r, y) => [...r].forEach((v, x) => v === "#" && px.push([x, y + TOP])));
    if (acc) {
      const off = Math.floor((w - 5) / 2);
      MARK[acc[1]].forEach((r, y) => [...r].forEach((v, x) => v === "#" && px.push([x + off, y])));
    }
    if (c === "Ç") px.push([2, TOP + 7], [1, TOP + 8]);
    g = { w, px };
  }
  cache.set(ch, g);
  return g;
}

export function textWidth(s: string, scale = 1): number {
  if (!s) return 0;
  return ([...s].reduce((w, ch) => w + glyph(ch).w + 1, 0) - 1) * scale;
}

/** Quebra em linhas que cabem em `maxW` px. */
export function wrap(s: string, maxW: number, scale = 1): string[] {
  const lines: string[] = [];
  let cur = "";
  for (const word of s.split(/\s+/).filter(Boolean)) {
    const next = cur ? `${cur} ${word}` : word;
    if (textWidth(next, scale) <= maxW || !cur) cur = next;
    else { lines.push(cur); cur = word; }
  }
  if (cur) lines.push(cur);
  return lines;
}
